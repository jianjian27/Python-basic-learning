#字符串拼接
#+号可以用来拼接两个字符串，但是无法将非字符串与字符串进行拼接，非字符串类型需要转换为字符串类型
s1 = "没""绷住"
print(s1)
s2 = "几天"
print("这" + s2 + s1)

name = "陈兆睿"
age = 21#字符串拼接时需要通过str()转为字符串类型
major = "电子科学与技术"
hobby = "..."
print("大家好，我是" + name + "," + "今年" + str(age) + "岁，学习的专业是" + major + ",爱好" + hobby)

#字符串格式化
#通过 %占位符 的形式完成字符串和变量的快速拼接。
print("大家好，我是 %s ，今年 %s 岁，这 %s %s" % (name,age,s2,s1))
#还可通过f"内容{变量/表达式}"的形式来快速格式化
print(f"大家好，我是{name}")
print(f"hhh{name}{age}")

