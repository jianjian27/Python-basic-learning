# 记录一些信息，这些信息不能被修改，只能查询
# 元组一旦定义完成，不可修改。与列表的区别
# 元组是不可变的序列，类似于列表，但创建后不能修改
# 可以存储不同类型的元素
# 元素可以重复，有序，不可以修改，支持索引访问，切片
# 元组使用 "()" 来定义

# 常用方法
# count():统计某元素在元组中出现的次数
# index():查找某个元素在元组中第一次出现的索引位置

t1 = (80,95,78,50,76,80,85,20)
print(t1)
print(type(t1))
print(t1[0],t1[2])
print(t1[2::2])#切片

print(t1.count(80))
print(t1.index(80))

t2 = ()

t3 = (1,)#定义单个元素的元组，需要加" , "表明是定义元组