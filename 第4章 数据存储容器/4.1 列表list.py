# 列表 list
# 一次性可以存储多个数据（元素）
# 列表名称 = [元素1，元素2，元素3...]
# 可以存储不同类型的元素
# 元素有序，可以重复，可以修改
# 下标，索引，从0开始，s[0],s[1]...
# 反向索引，最后一个元素记为s[-1],反向依次为s[-1],s[-2]...
# 指定索引超出范围，会报错
a = [1,2,"hhh",True]
print(a)
print(a[0])
print(type(a))

# 元素获取
print(a[2])
print(a[-1])

# 元素修改
a[1] = 7
print(a)

# 元素删除 del
del a[1]
print(a)

for i in a:
    print(i)

# 列表切片，列表，字符串，元组都支持切片操作
# 截取其中一部分
# 序列数据[开始索引:结束索引:步长]，不包含结束索引位置对应的元素，未指定默认开始为0，结束直至末尾，步长为1
# 正向索引，反向索引，混合用都可以
# 除第一个:不能省略,其它部分可以进行省略
