# 面向过程编程
# 核心思想:把一个需求分解成一系列要执行的步骤,然后按照步骤依次执行这些任务(关注的是流程、步骤)
# 适用场景：面向过程编辑非常直接，适合简单，线性的任务
#
# 面向对象编程
# 对象可以理解为现实中具体的人/物在程序中的数字化身(万物皆对象)
# 把一个人/物的特征和功能打包到一起，是面向对象编程的基本单元，属性和方法
# 关注的是谁来帮我做这件事
#
# 类与对象
# 类：描述的是一组具有相同属性(特征)和方法(功能/行为)的模版
# 对象：对象是类的实例，是基于类创建出来的(实例对象)
# 对象是由类创建出来的，创建对象的过程，也称对象的实例化，一个类可以创建无数个对象


