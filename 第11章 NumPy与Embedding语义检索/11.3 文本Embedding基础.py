# 11.7 文本 Embedding 基础
# 本节不加载真实模型，先理解文本如何变成向量，以及这种向量究竟表示什么。真实模型调用将在 11.9 SentenceTransformers基础 中完成。
# 1. 什么是文本 Embedding
# 文本 Embedding 是一个映射：

# 例如：
# “本文使用李雅普诺夫函数证明系统稳定。”
# 经过模型编码后，可能得到一个 384 维向量：
# [0.013, -0.027, 0.041, ..., 0.008]
# 我们不需要自己决定这些数值。它们由训练好的模型根据文本计算。
# 2. Embedding 不是随机向量
# 前一节使用的向量：
# [3.0, 4.0, 0.0]
# 是为了练习归一化和 Top-K 而手工构造的，不具有真实文本语义。
# 真实过程是：
# Chunk文本
# → Tokenizer处理
# → Embedding模型推理
# → 固定维度向量
# 例如：
# texts = [
#     "本文使用李雅普诺夫函数证明系统稳定。",
#     "数值实验采用四阶Runge-Kutta方法。",
# ]
#
# vectors = model.encode(texts)
# 假设模型输出 384 维向量：
# vectors.shape
# # (2, 384)
# 这里：
# vectors[0]对应texts[0]
# vectors[1]对应texts[1]
# 模型通常按输入顺序返回向量，因此不能在编码后随意打乱文本与向量的对应关系。
# 3. Embedding 表示的是什么
# Embedding 试图把文本的整体含义表示成向量空间中的位置。
# 例如：
# 文本A：如何证明系统稳定？
# 文本B：论文采用了什么稳定性分析方法？
# 文本C：数值实验的积分步长是多少？
# 虽然文本 A 和文本 B 使用的词语不完全相同，但语义接近，因此理想情况下：
# \[
# \operatorname{sim}(A,B)>
# \operatorname{sim}(A,C)
# \]
# 模型可能将 A 和 B 映射到相近方向，而把 C 映射到更远的方向。
# “相近”通常通过余弦相似度衡量：
# \[
# \cos(a,b)=
# \frac{a^\mathsf Tb}
# {\lVert a\rVert_2\lVert b\rVert_2}
# \]
# 如果模型已经输出归一化向量，就可以直接计算：
# similarity = vector_a @ vector_b
# 4. 单个维度通常不能直接解释
# 假设某个模型输出：
# vector.shape == (384,)
# 不能简单认为：
# 第0维 = 稳定性
# 第1维 = 混沌
# 第2维 = 数值实验
# Embedding 的语义一般分布在许多维度之间。某个维度单独看通常没有清晰的人类含义。
# 我们主要关心向量之间的几何关系，而不是解释每个坐标：
# - 方向是否接近；
# - 余弦相似度多大；
# - 哪些候选向量最接近查询；
# - 相关 Chunk 能否进入 Top-K。
# 5. Embedding 不是摘要
# 以下两者不同：
# 摘要：
# 用自然语言压缩原文，保留主要信息。
#
# Embedding：
# 把文本转换为固定维度的数值向量。
# Embedding 向量不能直接当作文字阅读：
# [0.013, -0.027, 0.041, ...]
# 它主要用于：
# - 语义检索；
# - 相似文本匹配；
# - 聚类；
# - 分类特征；
# - 去重或近似重复检测。
# 在当前项目中，我们只关注语义检索。
# 6. 关键词检索和 Embedding 检索
# 关键词检索
# 查询：
# 如何证明同步误差收敛？
# 论文原文：
# 利用李雅普诺夫稳定性理论可知，误差系统最终渐近稳定。
# 两者没有完全相同的关键表达：
# 查询：证明、同步误差、收敛
# 原文：李雅普诺夫、误差系统、渐近稳定
# 简单关键词匹配可能无法找到它。
# Embedding 检索
# Embedding 模型尝试识别：
# “误差收敛”
# 与
# “误差系统渐近稳定”
# 在该语境下具有相关含义，因此可能给出较高相似度。
# 对比：
# 特性	关键词检索	Embedding 检索
# 依赖相同词语	较强	较弱
# 识别改写表达	较弱	较强
# 精确匹配公式或参数名	较强	不一定可靠
# 理解整体自然语言语义	较弱	较强
# 结果可解释性	较直接	需要结合分数和原文
#
#
# Embedding 并不是在所有方面都优于关键词检索。
# 例如用户查询：
# 参数 a_17 的取值是多少？
# 精确的符号、公式编号、参数名和数值有时更适合关键词或结构化检索。后续项目可能采用混合检索，但当前阶段先实现 Embedding 语义检索。
# 7. 模型决定向量空间
# Embedding 向量没有脱离模型而独立存在。
# 以下做法是错误的：
# Chunk使用模型A编码
# Query使用模型B编码
# 即使两个模型都输出 384 维，它们也可能使用完全不同的向量空间。相同维度不代表可以比较。
# 正确要求是：
# 相同模型
# 相同模型版本
# 相同输入格式
# 相同归一化配置
# 兼容的Query和Passage编码方式
# 如果项目更换 Embedding 模型，通常需要重新编码所有 Chunk。
# 因此数据库不能只保存向量，还应记录：
# 模型标识
# 向量维度
# 是否归一化
# 编码格式
# Chunk内容哈希
# 8. Embedding 检索的完整逻辑
# 建立索引时：
# Chunk 0文本 ─→ Passage Embedding ─→ vector 0
# Chunk 1文本 ─→ Passage Embedding ─→ vector 1
# Chunk 2文本 ─→ Passage Embedding ─→ vector 2
#                                       ↓
#                             Chunk向量矩阵 C
# 用户查询时：
# 用户问题
#   ↓
# Query Embedding
#   ↓
# 查询向量 q
#   ↓
# scores = C @ q
#   ↓
# Top-K索引
#   ↓
# 根据索引或chunk_id找回原文
# 注意：Embedding 模型只生成向量，不负责：
# - 划分 Chunk；
# - 保存数据库；
# - 计算 Top-K；
# - 生成最终回答；
# - 判断论文结论是否正确。
# 这些是系统中其他组件的职责。
# 9. Embedding 的局限
# Embedding 相似度表示“模型认为语义接近”，不表示：
# - 两段话都是真实的；
# - 两段话逻辑等价；
# - 论文真的回答了用户问题；
# - 最高分一定足够相关；
# - 模型能准确区分所有否定、数字和数学符号。
# 例如：
# 系统是稳定的。
# 系统不是稳定的。
# 两句话包含大量相同词语，Embedding 可能仍然认为它们比较接近，尽管结论相反。
# 因此检索结果必须返回原文和出处，不能仅返回一个相似度分数。
# Embedding 主要判断 “是否在谈同一件事 ”，不可靠地判断：
# - 肯定与否定；
# - 支持与反驳；
# - 前提与结论；
# - 陈述是否真实。