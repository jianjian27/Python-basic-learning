# 当项目只有几十行代码时，可以把所有函数写在一个文件里。
# 但当项目变得复杂时，比如论文 RAG 项目会同时包含：
# PDF 读取
# 章节识别
# Chunk 构建
# 数据库
# Embedding
# 检索
# Agent
# 测试
# 如果全部放在一个文件里，会出现：
# 文件过长；
# 名称冲突；
# 修改一个功能影响其他功能；
# 很难测试；
# 很难复用。
# 所以 Python 使用：
# 模块：一个 .py 文件
# 包：一组相关模块组成的目录
# 把大型项目拆成多个有职责的部分。

# _init_.py 表明该目录是一个Python包，包被导入时执行初始化代码；可以暴露公共接口；可以定义包级别的变量。
#if __name__ == "__main__"
# 一个模块既可以被导入，也可以直接运行。
def main():
    print("程序入口")


if __name__ == "__main__":
    main()
# 当直接运行：
# python example.py
# 此时：
# __name__ == "__main__"
# 所以会执行：
# main()
# 但如果被其他文件导入：
# import example
# 此时：
# __name__ == "example"
# 因此不会自动执行 main()。
# 这个结构可以避免：
# 模块被导入时意外执行程序入口